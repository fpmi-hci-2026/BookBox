const EMOJI = { 1: "😞", 2: "😐", 3: "🙂", 4: "😊", 5: "🤩" };

function emotionCurve(levels) {
  const points = levels.map((lv, i) => [ (i + 0.5) * 100, 88 - (lv - 1) * 17 ]);
  const line = points.map((p) => p.join(",")).join(" ");
  const area = `50,100 ${line} 550,100`;
  return `<svg viewBox="0 0 600 100" preserveAspectRatio="none">
      <polygon points="${area}" fill="rgba(176,141,87,0.10)"/>
      <polyline points="${line}" fill="none" stroke="#B08D57" stroke-width="2.5" vector-effect="non-scaling-stroke" stroke-linejoin="round"/>
    </svg>`;
}

function cjmHtml(c) {
  const r = c.rows;
  const stageCells = STAGES.map((s) => `<div class="cell stage">${s}</div>`).join("");
  const row = (label, cells, cls = "") =>
    `<div class="row-label">${label}</div>` +
    cells.map((v) => `<div class="cell ${cls}">${v}</div>`).join("");

  const lists = (arr, cls) =>
    arr.map((v) => (v === "—" ? "—" : `<ul><li>${v}</li></ul>`)).join("");

  const dots = r.emotions
    .map((lv, i) => {
      const y = 88 - (lv - 1) * 17;
      return `<div class="emotion-dot" style="left:${((i + 0.5) / 6) * 100}%;top:${y}%">${EMOJI[lv]}</div>`;
    })
    .join("");

  return `<div class="cjm">
  <div class="cjm-head">
    <div>
      <h2>${c.name}</h2>
      <div class="goal">${c.subtitle}</div>
      <div class="goal" style="margin-top:8px;max-width:620px"><b>Цель:</b> ${c.goal}</div>
    </div>
    <div class="cjm-meta">${c.meta.map((m) => `<span class="chip">${m}</span>`).join("")}</div>
  </div>
  <div class="cjm-grid">
    <div class="row-label stage-row-label">Этап</div>${stageCells}
    ${row("Действия", r.actions)}
    ${row("Точки контакта", r.touch)}
    ${row("Мысли", r.thoughts.map((t) => `<span class="thought">${t}</span>`))}
    <div class="row-label">Эмоции</div>
    <div class="emotion-wrap">${emotionCurve(r.emotions)}${dots}</div>
    ${row("Боли", r.pains.map((p) => (p === "—" ? "—" : p)), "pain")}
    ${row("Решения BookBox", r.solutions, "solution")}
  </div>
</div>`;
}

